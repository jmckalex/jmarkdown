// Regenerate src/math-packages.js: the maths commands each of amsmath,
// amsfonts, amssymb and mathtools DEFINES that LaTeX itself does not — what
// MathJax accepts out of the box but a LaTeX document cannot use without the
// package (latex-lint.js warns when a document uses one and loads nothing that
// provides it).
//
// TeX decides, not a hand-kept list: every \name in the package's own .sty
// files is a candidate, and a name is the package's if it is undefined in a
// document that loads the package's prerequisites and defined in one that also
// loads the package. An ENVIRONMENT X is recorded as `endX`: LaTeX already has
// plain TeX's \cases and \pmatrix macros, but no \endcases or \endpmatrix,
// so `\begin{cases}` needs amsmath though \cases is defined (latex-lint.js
// looks up `end` + the name for a \begin). Re-run when TeX Live updates them:
//
//     node scripts/latex-math-packages.mjs

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

// package → [the .sty files to harvest names from, the packages it builds on]
const PACKAGES = {
	amsmath: [['amsmath.sty', 'amstext.sty', 'amsbsy.sty', 'amsopn.sty'], []],
	amsfonts: [['amsfonts.sty'], []],
	amssymb: [['amssymb.sty'], ['amsfonts']],
	latexsym: [['latexsym.sty'], []],
	mathtools: [['mathtools.sty'], ['amsmath']],
};

const kpse = (file) => execFileSync('kpsewhich', [file], { encoding: 'utf8' }).trim();
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'jmd-math-packages-'));

// The names, of those given, defined at \begin{document} with these packages.
function defined(packages, names) {
	const tex = [
		'\\documentclass{article}',
		...packages.map((p) => `\\usepackage{${p}}`),
		'\\newwrite\\jmdout',
		'\\immediate\\openout\\jmdout=defined.txt',
		// Name and meaning: LaTeX "defines" \Box and \Diamond as stubs that only
		// say they are not provided in base LaTeX (\not@base), which count as
		// undefined.
		'\\def\\jmdtest#1{\\expandafter\\ifx\\csname#1\\endcsname\\relax\\else\\immediate\\write\\jmdout{#1 \\expandafter\\meaning\\csname#1\\endcsname}\\fi}',
		'\\begin{document}',
		...names.map((n) => `\\jmdtest{${n}}`),
		'\\immediate\\closeout\\jmdout',
		'\\end{document}',
	].join('\n');
	fs.writeFileSync(path.join(work, 'probe.tex'), tex);
	execFileSync('pdflatex', ['-interaction=nonstopmode', '-halt-on-error', 'probe.tex'], { cwd: work, stdio: 'ignore' });
	return new Set(fs.readFileSync(path.join(work, 'defined.txt'), 'latin1').split('\n')
		.filter((line) => line && !line.includes('not@base'))
		.map((line) => line.split(' ')[0]));
}

const out = {};
for (const [name, [files, base]] of Object.entries(PACKAGES)) {
	const candidates = new Set();
	for (const file of files) {
		const source = fs.readFileSync(kpse(file), 'latin1');
		for (const m of source.matchAll(/\\([A-Za-z]+)/g)) candidates.add(m[1]);
		// Environments, starred ones included, as their \end macro.
		for (const m of source.matchAll(/\\(?:re)?newenvironment\s*\{([A-Za-z]+\*?)\}/g)) candidates.add(`end${m[1]}`);
		for (const m of source.matchAll(/(?:\\@namedef\s*\{|\\csname\s*)(?:end)?([A-Za-z]+\*?)(?:\}|\s*\\endcsname)/g)) candidates.add(`end${m[1]}`);
	}
	const names = [...candidates].sort();
	const before = defined(base, names);
	const after = defined([...base, name], names);
	out[name] = names.filter((n) => after.has(n) && !before.has(n));
	console.log(`${name}: ${out[name].length} commands`);
}

const version = execFileSync('pdflatex', ['--version'], { encoding: 'utf8' }).split('\n')[0];
const body = Object.entries(out)
	.map(([name, list]) => `\t${name}: new Set(${JSON.stringify(list).replace(/","/g, '", "')}),`)
	.join('\n');
fs.writeFileSync(new URL('../src/math-packages.js', import.meta.url), `// GENERATED by scripts/latex-math-packages.mjs — do not edit.
// ${version}
//
// The maths commands each package defines that LaTeX itself does not: a name
// in amssymb's set is undefined in a document that loads amsfonts and defined
// once amssymb is loaded too (mathtools likewise over amsmath). latex-lint.js
// warns when a document uses one and loads nothing that provides it.

export const MATH_PACKAGE_COMMANDS = {
${body}
};
`);
fs.rmSync(work, { recursive: true, force: true });
